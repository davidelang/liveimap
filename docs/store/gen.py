def vd_paths(shps,ind='        '):
    o=[]
    for d,fill,st,sw in shps:
        a=[f'android:pathData="{d}"']
        a.append(f'android:fillColor="{fill}"' if fill else 'android:fillColor="#00000000"')
        if st: a+= [f'android:strokeColor="{st}"',f'android:strokeWidth="{sw}"','android:strokeLineJoin="round"' if sw==5.2 else 'android:strokeLineJoin="miter"']
        if d is TEXT and fill: a.append('android:fillType="evenOdd"')
        o.append(ind+'<path\n'+ind+'    '+('\n'+ind+'    ').join(a)+' />')
    return '\n'.join(o)
