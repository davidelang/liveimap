class Flat(BasePen):
    def __init__(s,gs): super().__init__(gs); s.c=[]; s.cur=None
    def _moveTo(s,p): s.cur=[p]; s.c.append(s.cur)
    def _lineTo(s,p): s.cur.append(p)
    def _curveToOne(s,a,b,p):
        p0=s.cur[-1]
        for t in np.linspace(0,1,17)[1:]:
            u=1-t; s.cur.append(tuple(u**3*np.array(p0)+3*u*u*t*np.array(a)+3*u*t*t*np.array(b)+t**3*np.array(p)))
    def _qCurveToOne(s,a,p):
        p0=s.cur[-1]
        for t in np.linspace(0,1,13)[1:]:
            u=1-t; s.cur.append(tuple(u*u*np.array(p0)+2*u*t*np.array(a)+t*t*np.array(p)))
    def _closePath(s): pass
